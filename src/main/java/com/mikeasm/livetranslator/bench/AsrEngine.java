package com.mikeasm.livetranslator.bench;

import java.util.List;

/**
 * Один движок распознавания на стенде.
 * <p>
 * Движок отвечает только за «услышать кусок звука». Нарезку записи, смещение
 * времён, замер длительности и обработку ошибок берёт на себя {@link Bench}:
 * иначе каждый новый движок пришлось бы писать целиком, и стенд сравнивал бы
 * заодно качество этих реализаций.
 */
public interface AsrEngine {

    /** Короткое имя для файлов и таблиц. */
    String id();

    /** Как движок называется в отчёте. */
    String title();

    /**
     * Почему движок пропущен (нет ключа, нет настройки) или пустая строка,
     * если он готов работать.
     */
    String skipReason();

    /** Предел длины одного запроса: у каждого сервиса он свой. */
    int maxChunkMs();

    /** Распознаёт кусок. Времена сегментов — от начала куска, не записи. */
    List<Transcript.Segment> transcribe(AudioFile.Clip clip) throws Exception;

    /** Чем движок берёт деньги — попадает в отчёт как предупреждение. */
    default String priceNote() {
        return "";
    }

    default void close() {}
}
