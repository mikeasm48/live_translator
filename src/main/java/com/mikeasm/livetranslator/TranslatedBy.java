package com.mikeasm.livetranslator;

/**
 * Каким путём получен перевод.
 * <p>
 * Пометка нужна, чтобы счёт за облако читался однозначно. Обычный переводчик
 * включается только тогда, когда языковая модель не ответила, — и по одному
 * счёту не отличить «модель иногда падала» от «кто-то выключил модель в
 * настройках». В расшифровке это видно построчно.
 */
public enum TranslatedBy {

    /** Языковая модель — основной путь. */
    MODEL("модель"),

    /** Обычный Translate: модель не ответила или выключена. */
    PLAIN("переводчик"),

    /** Ничего не переводили: говорили на языке перевода. */
    SOURCE("");

    private final String label;

    TranslatedBy(String label) {
        this.label = label;
    }

    /** Как путь называется в расшифровке; пусто, если перевода не было. */
    public String label() {
        return label;
    }
}
